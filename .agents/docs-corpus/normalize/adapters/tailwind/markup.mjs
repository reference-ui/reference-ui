/**
 * Source-level cleanup for tailwindcss.com MDX, run before the shared converter.
 * It removes the module statements and reads the title and description exports,
 * then converts the markup the shared converter cannot read: template-literal
 * code examples, the props tables (whose rows can be template literals), raw
 * HTML tables and headings, images, and inline tags. Live previews are dropped,
 * keeping only their demo components for the hooks to inline. Fenced code is
 * never touched. Text stays verbatim: only markup changes.
 */

import { readOpenTag } from './jsx.mjs'

export const TABLE_NOTE = '> Table: the rows are generated by code in the source and are not reproduced here.'

const META = /^export const (title|description)\s*=\s*("(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*'|`[^`]*`)\s*;?[ \t]*$/gm
const IMPORT = /^import\s[\s\S]*?\sfrom\s+['"][^'"\n]+['"];?[ \t]*$/gm
const CODE_BLOCK = /<CodeBlock\b((?:\s+[\w-]+="[^"]*")*)\s+example=\{(\w*)`((?:\\[\s\S]|[^\\`])*)`\s*\}\s*\/>/g
const API_TABLE = /<ApiTable\s+rows=\{([\s\S]*?)\}\s*\/>/g
const IMG = /<img\b[^>]*?\/>/g
const HEADING = /^[ \t]*<h([1-6])\b[^>]*>\s*(?:<a\b[^>]*>)?\s*([^<\n]*?)\s*(?:<\/a>)?\s*<\/h\1>/gm
const TABLE = /^[ \t]*<table\b[\s\S]*?^[ \t]*<\/table>/gm
const PREVIEW_OPEN = /^[ \t]*(\{[ \t]*)?<([a-z][\w-]*)(?=[\s/>])/gm
const HELD = /\u0000(\d+)\u0000/g

/** Content fragments from the site's content module: unresolved here, so only their tag is kept. */
const FRAGMENTS = [
  'ResponsiveDesign',
  'UsingACustomValue',
  'CustomizingYourSpacingScale',
  'CustomizingYourTheme',
  'CustomizingYourThemeColors',
  'TargetingSpecificStates',
]

/** Lowercase tags that sit inside a sentence: they are inline markup, not previews. */
const INLINE_TAGS = new Set([
  'a', 'abbr', 'b', 'br', 'cite', 'code', 'del', 'em', 'i', 'ins', 'kbd', 'mark', 'q', 's', 'samp', 'small', 'strong', 'sub', 'sup', 'u', 'var',
])

const ENTITIES = { '&lt;': '<', '&gt;': '>', '&amp;': '&', '&quot;': '"', '&#39;': "'", '&nbsp;': ' ' }

/** Splits MDX into prose and fenced-code segments, using the converter's fence rules. */
export function splitFences(text) {
  const segments = []
  let prose = []
  let fence = null
  for (const line of text.split('\n')) {
    if (!fence) {
      const open = line.match(/^\s*(`{3,}|~{3,})(.*)$/)
      if (open && !(open[1][0] === '`' && open[2].includes('`'))) {
        segments.push({ fence: false, text: prose.join('\n') })
        prose = []
        fence = { mark: open[1], lines: [line] }
      } else {
        prose.push(line)
      }
      continue
    }
    fence.lines.push(line)
    const close = line.match(/^\s*(`{3,}|~{3,})\s*$/)
    if (close && close[1][0] === fence.mark[0] && close[1].length >= fence.mark.length) {
      segments.push({ fence: true, text: fence.lines.join('\n') })
      fence = null
    }
  }
  if (fence) segments.push({ fence: true, text: fence.lines.join('\n') })
  segments.push({ fence: false, text: prose.join('\n') })
  return segments
}

/** A JS template literal's cooked text for the escapes these docs use (`\[` is `[`). */
export function unescapeTemplate(text) {
  return text.replace(/\\([\s\S])/g, '$1')
}

/** Removes the common leading indent and the blank lines around a block of text. */
export function dedent(text) {
  const lines = text.split('\n')
  const indents = lines.filter(line => line.trim()).map(line => line.match(/^\s*/)[0].length)
  const least = indents.length ? Math.min(...indents) : 0
  return lines
    .map(line => line.slice(Math.min(least, line.match(/^\s*/)[0].length)))
    .join('\n')
    .replace(/^\s*\n/, '')
    .replace(/\n\s*$/, '')
}

/** A fenced block whose fence is longer than any backtick run inside it. */
export function codeFence(lang, body) {
  const longest = Math.max(2, ...[...body.matchAll(/`+/g)].map(m => m[0].length))
  const mark = '`'.repeat(Math.max(3, longest + 1))
  return [`${mark}${lang}`, ...body.replace(/\n+$/, '').split('\n'), mark].join('\n')
}

/** The fenced blocks in converted Markdown, as arrays of lines (fence lines included). */
export function fencedBlocks(markdown) {
  return splitBlocks(markdown)
    .filter(part => part.fenced)
    .map(part => part.lines)
}

/** Splits converted Markdown into fenced and unfenced line runs, in order. */
export function splitBlocks(markdown) {
  const parts = []
  let run = []
  let fence = null
  for (const line of markdown.split('\n')) {
    if (!fence) {
      const open = line.match(/^(`{3,}|~{3,})/)
      if (open) {
        if (run.length) parts.push({ fenced: false, lines: run })
        run = []
        fence = { mark: open[1], lines: [line] }
      } else {
        run.push(line)
      }
      continue
    }
    fence.lines.push(line)
    if (line.trim() === fence.mark) {
      parts.push({ fenced: true, lines: fence.lines })
      fence = null
    }
  }
  if (fence) parts.push({ fenced: true, lines: fence.lines })
  if (run.length) parts.push({ fenced: false, lines: run })
  return parts
}

/**
 * The string rows of a literal array-of-arrays expression such as
 * `[["a", "b"], ["c", "d"]]`. Returns null for anything computed (a spread, a
 * call, a template with `${}`), because the rows cannot be read without running code.
 */
export function literalRows(source) {
  const text = source.trim()
  const rows = []
  let depth = 0
  let row = null
  let i = 0
  while (i < text.length) {
    const ch = text[i]
    if (ch === '"' || ch === "'" || ch === '`') {
      let j = i + 1
      let value = ''
      while (j < text.length && text[j] !== ch) {
        if (ch === '`' && text[j] === '$' && text[j + 1] === '{') return null
        if (text[j] === '\\') {
          value += text[j + 1] ?? ''
          j += 2
          continue
        }
        value += text[j]
        j++
      }
      if (j >= text.length || depth !== 2 || !row) return null
      row.push(value)
      i = j + 1
      continue
    }
    if (ch === '[') {
      depth++
      if (depth === 2) row = []
    } else if (ch === ']') {
      if (depth === 2) {
        rows.push(row)
        row = null
      }
      depth--
    } else if (ch !== ',' && !/\s/.test(ch)) {
      return null
    }
    i++
  }
  return depth === 0 ? rows : null
}

/** An inline code span, with a longer delimiter when the code holds a backtick. */
export function codeSpan(text) {
  if (!text.includes('`')) return `\`${text}\``
  return `\`\` ${text} \`\``
}

function decodeEntities(text) {
  return text.replace(/&(?:lt|gt|amp|quot|#39|nbsp);/g, entity => ENTITIES[entity])
}

/**
 * Text with JSX string expressions unwrapped and markup removed. An expression's
 * string is kept whole: `{'(<custom-property>)'}` keeps its angle brackets.
 */
function plainText(html) {
  const held = []
  const guarded = html.replace(/\{\s*(['"`])([\s\S]*?)\1\s*\}/g, (_, quote, value) => {
    held.push(value)
    return `\u0002${held.length - 1}\u0002`
  })
  const text = decodeEntities(guarded.replace(/<[^>]*>/g, '').replace(/\s+/g, ' ').trim())
  return text.replace(/\u0002(\d+)\u0002/g, (_, index) => held[Number(index)])
}

/** Inline markup in one cell or sentence: code, emphasis and links become Markdown. */
function inlineMarkdown(html) {
  // Every piece that must not be read as markup is held by index until the tags are gone.
  const held = []
  const hold = piece => {
    held.push(piece)
    return `\u0002${held.length - 1}\u0002`
  }
  const text = html
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, '')
    .replace(/<br\s*\/?>/g, ' ')
    .replace(/<code\b[^>]*>([\s\S]*?)<\/code>/g, (_, code) => {
      const plain = plainText(code)
      return hold(plain ? codeSpan(plain) : '')
    })
    .replace(/<(strong|b)\b[^>]*>([\s\S]*?)<\/\1>/g, '**$2**')
    .replace(/<(em|i)\b[^>]*>([\s\S]*?)<\/\1>/g, '*$2*')
    .replace(/<a\b[^>]*href="([^"]*)"[^>]*>([\s\S]*?)<\/a>/g, '[$2]($1)')
    .replace(/\{\s*(['"])([^'"]*)\1\s*\}/g, (_, quote, value) => hold(value))
  const plain = decodeEntities(text.replace(/<[^>]*>/g, '').replace(/\s+/g, ' ').trim())
  return plain.replace(/\u0002(\d+)\u0002/g, (_, index) => held[Number(index)]).replace(/\|/g, '\\|')
}

/** A Markdown table from a hand-written `<table>`: the first row is the header. */
export function tableMarkdown(html) {
  const rows = [...html.matchAll(/<tr\b[^>]*>([\s\S]*?)<\/tr>/g)].map(([, inner]) =>
    [...inner.matchAll(/<(th|td)\b[^>]*>([\s\S]*?)<\/\1>/g)].map(([, , cell]) => inlineMarkdown(cell))
  )
  if (!rows.length) return ''
  const width = Math.max(...rows.map(row => row.length))
  const line = cells => `| ${[...cells, ...Array(width - cells.length).fill('')].join(' | ')} |`
  return [line(rows[0]), line(Array(width).fill('---')), ...rows.slice(1).map(line)].join('\n')
}

/** The top-level items of an array expression body, split at commas outside strings and brackets. */
function splitItems(inner) {
  const parts = []
  let depth = 0
  let quote = null
  let current = ''
  for (let i = 0; i < inner.length; i++) {
    const c = inner[i]
    if (quote) {
      current += c
      if (c === '\\') current += inner[++i] ?? ''
      else if (c === quote) quote = null
      continue
    }
    if (c === '"' || c === "'" || c === '`') quote = c
    else if ('([{'.includes(c)) depth++
    else if (')]}'.includes(c)) depth--
    else if (c === ',' && depth === 0) {
      parts.push(current)
      current = ''
      continue
    }
    current += c
  }
  parts.push(current)
  return parts.map(part => part.trim()).filter(Boolean)
}

/** Each item of a props-table rows array: a literal `[name, css]` row, or `computed` for anything generated by code. */
function rowItems(source) {
  const text = source.trim()
  if (!text.startsWith('[') || !text.endsWith(']')) return null
  return splitItems(text.slice(1, -1)).map(part => {
    const rows = literalRows(`[${part}]`)
    return rows && rows.length === 1 && rows[0].length === 2 ? { row: rows[0] } : { computed: true }
  })
}

/**
 * The props table from `<ApiTable rows={...} />`: literal rows as a Class and
 * Styles table, with one note wherever rows are generated by code.
 */
function apiTableMarkdown(body) {
  const items = rowItems(body)
  if (!items || !items.length) return TABLE_NOTE
  const cell = text => codeSpan(text.replace(/\s+/g, ' ').replace(/\|/g, '\\|'))
  const blocks = []
  let run = []
  const flush = () => {
    if (run.length) {
      blocks.push(['| Class | Styles |', '| --- | --- |', ...run.map(([name, css]) => `| ${cell(name)} | ${cell(css)} |`)].join('\n'))
      run = []
    }
  }
  for (const item of items) {
    if (!item.computed) {
      run.push(item.row)
      continue
    }
    flush()
    if (blocks[blocks.length - 1] !== TABLE_NOTE) blocks.push(TABLE_NOTE)
  }
  flush()
  return blocks.join('\n\n')
}

/** The body of a tagged template in a file, such as the `html` snippet of `html\`...\``. */
export function templateBody(source, tag) {
  const match = source.match(new RegExp(`\\b${tag}\`((?:\\\\[\\s\\S]|[^\\\\\`])*)\``))
  return match ? dedent(unescapeTemplate(match[1])) : null
}

/** Index of the `>` that ends the open tag starting at `start`, skipping quoted text and braces. */
function openTagEnd(text, start) {
  let quote = null
  let braces = 0
  for (let i = start + 1; i < text.length; i++) {
    const c = text[i]
    if (quote) {
      if (c === quote) quote = null
      continue
    }
    if (c === '"' || c === "'" || c === '`') quote = c
    else if (c === '{') braces++
    else if (c === '}') braces--
    else if (c === '>' && braces <= 0) return i
  }
  return -1
}

/** Index just past the closing tag of the element `name` opened at `start`, or -1. */
function elementEnd(text, start, name) {
  const open = `<${name}`
  const close = `</${name}>`
  let depth = 0
  let i = start
  while (i < text.length) {
    if (text.startsWith(close, i)) {
      depth--
      i += close.length
      if (depth === 0) return i
      continue
    }
    if (text.startsWith(open, i) && /[\s/>]/.test(text[i + open.length] ?? '')) {
      const end = openTagEnd(text, i)
      if (end === -1) return -1
      const selfClosing = text[end - 1] === '/'
      if (i === start && selfClosing) return end + 1
      if (!selfClosing) depth++
      i = end + 1
      continue
    }
    i++
  }
  return -1
}

/** The self-closing capitalized tags in a block: demo components the hooks still need. */
function selfClosingComponents(block) {
  const found = []
  const re = /<[A-Z][\w.]*(?=[\s/>])/g
  let m
  while ((m = re.exec(block))) {
    const end = openTagEnd(block, m.index)
    if (end !== -1 && block[end - 1] === '/') {
      found.push(block.slice(m.index, end + 1))
      re.lastIndex = end + 1
    }
  }
  return found
}

/**
 * Each content fragment's open tag, with its props kept as base64 JSON in
 * `data-props`. The JSX reader reads the props, so a multi-line value or a
 * template literal cannot hide the children that follow.
 */
function captureFragments(text) {
  const re = new RegExp(`<(${FRAGMENTS.join('|')})(?=[\\s/>])`, 'g')
  let out = ''
  let pos = 0
  let m
  while ((m = re.exec(text))) {
    const open = readOpenTag(text, m.index)
    const data = Buffer.from(JSON.stringify(open.attrs), 'utf8').toString('base64')
    out += text.slice(pos, m.index) + (open.selfClosing ? `<${m[1]} data-props="${data}" />` : `<${m[1]} data-props="${data}">`)
    pos = open.end
    re.lastIndex = pos
  }
  return out + text.slice(pos)
}

/**
 * Drops live previews: lowercase elements at the start of a line (a `div`, `svg`,
 * `p`) with their whole contents. Previews are markup, not text, so only the
 * self-closing capitalized demos inside them are kept, for their hooks.
 * `details` and `summary` are FAQ content and are converted, not dropped.
 */
function dropPreviewBlocks(text) {
  const opener = new RegExp(PREVIEW_OPEN.source, 'gm')
  let out = ''
  let pos = 0
  let m
  while ((m = opener.exec(text))) {
    const name = m[2]
    if (INLINE_TAGS.has(name) || name === 'details' || name === 'summary') continue
    const start = m.index + m[0].length - name.length - 1
    const end = elementEnd(text, start, name)
    if (end === -1) continue
    const kept = selfClosingComponents(text.slice(start, end))
    out += text.slice(pos, m.index) + (kept.length ? `${kept.join('\n')}\n` : '')
    pos = end
    opener.lastIndex = end
  }
  return out + text.slice(pos)
}

/** Inline HTML and JSX tags in prose, as Markdown. */
function inlineTags(text) {
  return text
    .replace(/<code\b[^>]*>([\s\S]*?)<\/code>/g, (_, code) => codeSpan(plainText(code)))
    .replace(/<(strong|b)\b[^>]*>([\s\S]*?)<\/\1>/g, '**$2**')
    .replace(/<(em|i)\b[^>]*>([\s\S]*?)<\/\1>/g, '*$2*')
    .replace(/<a\b[^>]*href="([^"]*)"[^>]*>([\s\S]*?)<\/a>/g, '[$2]($1)')
}

function unquote(literal) {
  if (literal.startsWith('`')) return literal.slice(1, -1)
  return unescapeTemplate(literal.slice(1, -1))
}

/** The markup transforms for one prose segment. Fenced code is never passed in. */
function proseTransforms(text, meta, held) {
  let out = text.replace(META, (_, key, value) => {
    meta[key] = unquote(value)
    return ''
  })
  out = out.replace(IMPORT, '')
  out = out.replace(/<\/\s+([A-Z][\w.]*)\s*>/g, '</$1>')
  out = out.replace(/([^\s])(<\/[A-Z][\w.]*>)/g, '$1\n$2')
  out = out.replace(/^(\s*)\{(<[A-Z][^\n]*?\/>)\}\s*$/gm, '$1$2')
  out = out.replace(CODE_BLOCK, (_, attrs, lang, body) => {
    held.push(codeFence(lang, dedent(unescapeTemplate(body))))
    return `\n\u0000${held.length - 1}\u0000\n`
  })
  out = out.replace(API_TABLE, (_, body) => `\n${apiTableMarkdown(body)}\n`)
  out = out.replace(IMG, tag => {
    const alt = tag.match(/\balt="([^"]*)"/)?.[1].trim()
    return alt ? `\n> Image: ${alt}\n` : ''
  })
  out = out.replace(HEADING, (_, level, title) => `\n${'#'.repeat(Number(level))} ${title}\n`)
  out = out.replace(TABLE, table => `\n${tableMarkdown(table)}\n`)
  out = captureFragments(out)
  out = dropPreviewBlocks(out)
  out = out.replace(/^([ \t]*)<details\b[^>]*>/gm, '$1<Details>').replace(/^([ \t]*)<\/details>/gm, '$1</Details>')
  out = out.replace(/^([ \t]*)<summary\b[^>]*>/gm, '$1<summary>')
  out = inlineTags(out)
  out = out.replace(/^\s*[{}]\s*$/gm, '')
  return out
}

/**
 * The body of one MDX page as the converter needs it: module statements gone,
 * the title and description read out, and the markup above converted.
 * Returns { title, description, text }; `text` is the body only.
 */
export function cleanMdx(source) {
  const meta = {}
  const held = []
  const segments = splitFences(source.replace(/\r\n?/g, '\n'))
  const text = segments
    .map(seg => (seg.fence ? seg.text : proseTransforms(seg.text, meta, held)))
    .join('\n')
    .replace(HELD, (_, index) => held[Number(index)])
  return { title: meta.title, description: meta.description, text: text.trim() }
}
