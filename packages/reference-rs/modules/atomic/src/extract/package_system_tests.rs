//! Unit pins for reading a package directory's system.
//!
//! The published file parses to its name and stream names (streams first,
//! the name alone when none), malformed text fails naming the file, and the
//! process memo hands back one shared system until the file's mtime moves.
//! On disk, a directory's verdict follows `exports["./baseSystem"]`, then the
//! conventional path; this compile's own generated tree and a linked project
//! directory borrowing the own runtime are own; an installed copy without a
//! system, and a linked one that never imports the runtime, are foreign even
//! when the own runtime resolves from them.

use std::fs;
use std::sync::Arc;
use std::time::{Duration, SystemTime};

use module_graph::DiskFs;
use shared::testing::ScratchWorkspace;

use super::{
    dir_verdict, installed_dir, package_name, parse_names, published, DirVerdict, PackageVerdict,
};
use crate::extract::own_runtime::{OwnCompile, OwnRoot};

const LIB_SHAPE: &str = "/** Generated by ref sync — do not edit manually */\n\
    export const baseSystem = {\n  \"name\": \"reference-ui\",\n  \"fragment\": \"x\",\n  \
    \"streams\": [{ \"name\": \"reference-icons\", \"tokens\": {} }, { \"name\": \"reference-ui\" }]\n}\n";

fn published_system(name: &str) -> String {
    format!("export const baseSystem = {{ \"name\": \"{name}\" }};\n")
}

/// A canonical scratch root, so verdicts compare canonical directories.
fn scratch(name: &str) -> (ScratchWorkspace, String) {
    let scratch = ScratchWorkspace::new(name);
    let root = fs::canonicalize(scratch.root()).expect("scratch root exists");
    (scratch, root.to_string_lossy().into_owned())
}

#[test]
fn published_names_read_streams_then_name() {
    let names = parse_names(LIB_SHAPE).expect("lib shape parses");
    assert_eq!(names.name, "reference-ui");
    assert_eq!(names.systems, vec!["reference-icons", "reference-ui"]);
    let bare = parse_names(&published_system("acme")).expect("bare shape parses");
    assert_eq!(bare.systems, vec!["acme"]);
    assert!(parse_names("export const other = {}").is_err());
    assert!(parse_names("export const baseSystem = { name: acme }").is_err());
}

#[test]
fn installed_dirs_end_at_the_package_name() {
    assert_eq!(
        installed_dir("/p/node_modules/acme-ui/dist/index.mjs"),
        Some("/p/node_modules/acme-ui")
    );
    assert_eq!(
        installed_dir("/p/node_modules/.pnpm/x@1/node_modules/@acme/ui/index.js"),
        Some("/p/node_modules/.pnpm/x@1/node_modules/@acme/ui")
    );
    assert_eq!(installed_dir("/p/packages/ui/src/index.ts"), None);
    assert_eq!(installed_dir("/p/node_modules/@acme"), None);
}

#[test]
fn the_memo_shares_a_system_until_its_mtime_moves() {
    let (_scratch, root) = scratch("published-memo");
    let path = format!("{root}/baseSystem.mjs");
    fs::write(&path, published_system("first")).expect("write system");
    let first = published(&path);
    assert!(Arc::ptr_eq(&first, &published(&path)));
    assert_eq!(first.names().map(|names| names.name.as_str()), Ok("first"));

    fs::write(&path, published_system("second")).expect("rewrite system");
    let later = SystemTime::now() + Duration::from_secs(5);
    let file = fs::File::options().write(true).open(&path).expect("open system");
    file.set_modified(later).expect("move mtime");
    let second = published(&path);
    assert!(!Arc::ptr_eq(&first, &second));
    assert_eq!(second.names().map(|names| names.name.as_str()), Ok("second"));

    fs::write(&path, "not a system").expect("break system");
    file.set_modified(later + Duration::from_secs(5)).expect("move mtime");
    let broken = published(&path);
    let error = broken.names().expect_err("malformed system fails");
    assert!(error.starts_with(&path), "{error}");
}

#[test]
fn published_systems_follow_exports_then_the_conventional_path() {
    let (scratch, root) = scratch("published-dirs");
    scratch.write(
        "exported/package.json",
        r#"{"exports":{"./baseSystem":{"types":"./out/system.d.mts","import":"./out/system.mjs"}}}"#,
    );
    scratch.write("exported/out/system.mjs", &published_system("exported"));
    scratch.write("exported/out/system.d.mts", "export {}");
    scratch.write("plain/package.json", r#"{"name":"plain"}"#);
    scratch.write(
        "plain/.reference-ui/system/baseSystem.mjs",
        &published_system("plain"),
    );
    scratch.write("types-only/package.json", r#"{"exports":{"./baseSystem":"./system.d.mts"}}"#);
    scratch.write("types-only/system.d.mts", "export {}");
    for (dir, name) in [("exported", "exported"), ("plain", "plain")] {
        let DirVerdict::Package(PackageVerdict::Published(system)) =
            dir_verdict(&DiskFs, &format!("{root}/{dir}"), None)
        else {
            panic!("{dir} publishes a system");
        };
        assert_eq!(system.names().map(|names| names.name.as_str()), Ok(name));
    }
    assert!(matches!(
        dir_verdict(&DiskFs, &format!("{root}/types-only"), None),
        DirVerdict::Package(PackageVerdict::Foreign)
    ));
}

#[cfg(unix)]
#[test]
fn the_own_runtime_is_own_only_for_linked_project_dirs() {
    let (scratch, root) = scratch("own-runtime");
    scratch.write(".reference-ui/react/package.json", r#"{"main":"./react.mjs"}"#);
    scratch.write(".reference-ui/react/react.mjs", "export {}");
    scratch.write(".reference-ui/system/package.json", r#"{"exports":{"./baseSystem":"./baseSystem.mjs"}}"#);
    scratch.write(".reference-ui/system/baseSystem.mjs", &published_system("own"));
    scratch.write("packages/ui/package.json", r#"{"name":"@acme/ui","main":"./dist/index.mjs"}"#);
    scratch.write("packages/ui/dist/index.mjs", "export { Div as Card } from '@reference-ui/react'\n");
    scratch.write("packages/icons/package.json", r#"{"name":"@acme/icons","main":"./index.mjs"}"#);
    scratch.write("packages/icons/index.mjs", "export const StarIcon = () => null\n");
    scratch.write("node_modules/lucide/package.json", r#"{"name":"lucide","main":"./index.mjs"}"#);
    scratch.write("node_modules/lucide/index.mjs", "import '@reference-ui/react'\n");
    fs::create_dir_all(format!("{root}/node_modules/@reference-ui")).expect("scope dir");
    std::os::unix::fs::symlink(
        format!("{root}/.reference-ui/react"),
        format!("{root}/node_modules/@reference-ui/react"),
    )
    .expect("link own runtime");
    let own = OwnRoot::at(&DiskFs, &root).expect("own root exists");
    let includes = |_: &str| false;
    let own = OwnCompile {
        root: &own,
        includes: &includes,
    };
    let verdict = |dir: &str, own: Option<&OwnCompile<'_>>| {
        dir_verdict(&DiskFs, &format!("{root}/{dir}"), own)
    };
    assert!(matches!(verdict("packages/ui", Some(&own)), DirVerdict::OwnRuntime));
    assert!(matches!(verdict(".reference-ui/system", Some(&own)), DirVerdict::OwnRuntime));
    assert!(matches!(
        verdict("packages/icons", Some(&own)),
        DirVerdict::Package(PackageVerdict::Foreign)
    ));
    assert!(matches!(
        verdict("node_modules/lucide", Some(&own)),
        DirVerdict::Package(PackageVerdict::Foreign)
    ));
    assert!(matches!(
        verdict("packages/ui", None),
        DirVerdict::Package(PackageVerdict::Foreign)
    ));
}

#[test]
fn package_name_drops_the_subpath_only() {
    assert_eq!(package_name("@reference-ui/lib/primitives"), "@reference-ui/lib");
    assert_eq!(package_name("@reference-ui/icons"), "@reference-ui/icons");
    assert_eq!(package_name("acme-ui/button"), "acme-ui");
    assert_eq!(package_name("acme-ui"), "acme-ui");
}
