/**
 * Workspace package (ATM-SITE-101, plan gap 1). `@acme/ui` resolves through
 * its pnpm link into this compile's own sources, so `Card` is traced and its
 * `bg` backs under own, alone or with lib composed, silently. The twin copies
 * the tree into a scratch workspace and gives `packages/ui` a published system
 * (`acme`): partly composed it warns at the tag naming the package and backs
 * nothing; with `acme` composed it backs `acme__bg_red` only.
 */
import fs from 'node:fs'
import path from 'node:path'
import { expect } from 'vitest'
import { compile, type NativeCompileRequest } from '../../../js/index.js'
import { createVirtualWorkspace } from '../../../../../testing/index.js'
import {
  getCaseInputDir,
  layerClassNames,
  LIB_SYSTEM_SPEC,
  wantBackings,
  type AtomicCaseSpec,
  type CompileResult,
} from '../../harness/helpers.js'

const CASE = 'ATM-SITE-101'
const UNBACKED = 'ATM-W-EXTERNAL-UNBACKED'
const OWN = {
  'bg:red': '@reference-ui/lib__bg_red',
  'p:1r': '@reference-ui/lib__p_1r',
}
const ACME_SYSTEM =
  '/** Generated by ref sync — do not edit manually */\n' +
  'export const baseSystem = {\n  "name": "acme"\n}\n'

/** Core's request over `root`: the primitive roster and `upstreamSystems` composed. */
function compileComposed(root: string, upstreamSystems: string[]): Promise<CompileResult> {
  const sourceRoot = path.resolve(root)
  const request: NativeCompileRequest & { upstreamSystems: string[] } = {
    schemaVersion: 2,
    spec: LIB_SYSTEM_SPEC,
    jsxHosts: ['Div'],
    upstreamSystems,
    sourceRoot,
    declarationRoot: sourceRoot,
    logs: ['proof'],
  }
  return compile(request)
}

/** Each style plan as `<system> <prop>:<value> <classes>`, sorted. */
function planRows(result: CompileResult): string[] {
  return (result.stylePlans ?? [])
    .map(p => `${p.system} ${p.prop}:${String(p.value)} ${p.declarations.map(d => d.className).join(',')}`)
    .sort()
}

/** Each unbacked warning as `<file>:<line> <message> | <help>`. */
function unbacked(result: CompileResult): string[] {
  return result.diagnostics
    .filter(d => d.code === UNBACKED)
    .map(d => `${path.basename(d.file ?? '')}:${d.line} ${d.message} | ${(d.help ?? []).join(' | ')}`)
}

/** The case tree after `packages/ui` ran its own sync, links kept verbatim. */
async function withPublishedUi<T>(run: (root: string) => Promise<T>): Promise<T> {
  const workspace = await createVirtualWorkspace({}, CASE)
  try {
    fs.cpSync(getCaseInputDir(CASE), workspace.rootDir, { recursive: true, verbatimSymlinks: true })
    workspace.writeFile('packages/ui/.reference-ui/system/baseSystem.mjs', ACME_SYSTEM)
    return await run(workspace.rootDir)
  } finally {
    await workspace.cleanup()
  }
}

const spec: AtomicCaseSpec = {
  id: CASE,
  async verify(result) {
    expect(result.tracedJsxHosts ?? []).toEqual(['Card'])
    expect(wantBackings(result, 'bg')).toEqual(['red own'])
    expect(result.css?.classes).toEqual(OWN)
    expect(result.diagnostics).toEqual([])

    const withLib = await compileComposed(getCaseInputDir(CASE), ['reference-ui'])
    expect(wantBackings(withLib, 'bg')).toEqual(['red own'])
    expect(planRows(withLib)).toEqual([
      '@reference-ui/lib bg:red @reference-ui/lib__bg_red',
      '@reference-ui/lib p:1r @reference-ui/lib__p_1r',
    ])
    expect(layerClassNames(withLib.stylesheet, 'utilities').has('reference-ui__bg_red')).toBe(false)
    expect(withLib.diagnostics).toEqual([])

    await withPublishedUi(async root => {
      const partial = await compileComposed(root, ['reference-ui'])
      expect(wantBackings(partial, 'bg')).toEqual(['red unbacked'])
      expect(planRows(partial)).toEqual(['@reference-ui/lib p:1r @reference-ui/lib__p_1r'])
      expect(unbacked(partial)).toEqual([
        "App.tsx:12 style props on <Card> will not paint: '@acme/ui' renders through its own " +
          "system 'acme', and no system in `extends` or `layers` backs it | " +
          "add '@acme/ui/baseSystem' to `extends` or `layers` in ui.config",
      ])

      const composed = await compileComposed(root, ['reference-ui', 'acme'])
      expect(wantBackings(composed, 'bg')).toEqual(['red acme'])
      expect(planRows(composed)).toEqual([
        '@reference-ui/lib p:1r @reference-ui/lib__p_1r',
        'acme bg:red acme__bg_red',
      ])
      const painted = layerClassNames(composed.stylesheet, 'utilities')
      expect(painted.has('acme__bg_red')).toBe(true)
      expect(painted.has('reference-ui__bg_red')).toBe(false)
      expect(composed.diagnostics).toEqual([])
    })
  },
}

export default spec
