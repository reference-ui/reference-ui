// literal-fragment.ts — the large local fragment for CORE-WATCH-32. It takes the world dir and writes
// `src/literal-tokens.ts`: eight thousand colour tokens spelled out literally, about 300 KB, so the fragment
// script each resync evaluates is itself large (the upstream's tokens reach it as a portable bundle, not as
// source). removeLiteralFragment deletes it; the world's .gitignore keeps it out of the tree.
import fs from 'node:fs'
import path from 'node:path'

const COUNT = 8000

export function literalFragmentPath(worldDir: string): string {
  return path.join(worldDir, 'src', 'literal-tokens.ts')
}

export function writeLiteralFragment(worldDir: string): void {
  const entries = Array.from(
    { length: COUNT },
    (_, i) => `    lit${i}: { value: '#${((i * 40503) % 0xffffff).toString(16).padStart(6, '0')}' },`,
  )
  const source = [
    '// Generated by CORE-WATCH-32 specs/literal-fragment.ts; never committed.',
    "import { tokens } from '@reference-ui/core'",
    '',
    'tokens({',
    '  colors: {',
    ...entries,
    '  },',
    '})',
    '',
  ].join('\n')
  fs.writeFileSync(literalFragmentPath(worldDir), source, 'utf8')
}

export function removeLiteralFragment(worldDir: string): void {
  fs.rmSync(literalFragmentPath(worldDir), { force: true })
}
