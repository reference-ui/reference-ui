// Native generator for the Core react entry plus its bound per-system types.
// It takes the system name, the compiled style prop names, the tracked
// primitives path, and the spec recipes, and emits the bound entry source
// plus the complete react.d.mts. The types bake narrows the primitive types per system:
// the compiled StylePropName union, SystemStyleObject css, and the typegen
// recipe-union variant (never when recipes are absent). Recipe declarations
// return one class string per slot when a config lists `slots`. The synced role
// decides the SyncedSystem register: a publisher declares it, a consumer
// fills it, and the default role keeps the pre-register output byte-identical.

import { ELEMENT_DOM_TAGS, ELEMENT_JSX_NAMES, ELEMENT_ROSTER } from '../../native/element-vocabulary.ts'
import type { SyncedRole } from '../../packager/synced-role.ts'

export interface ReactEntryInput {
  systemName: string
  stylePropNames: readonly string[]
  primitivesPath: string
}

export interface ReactTypesInput {
  stylePropNames: readonly string[]
  /** Raw spec recipes (name to RecipeDefinition JSON): stems the variant union. */
  recipes: Record<string, unknown>
  /** Synced role of the project; omitted means none, the pre-register output. */
  role?: SyncedRole
  /** Width breakpoints recipe classes are compiled for; omitted means `base` only. */
  recipeBreakpoints?: readonly string[]
}

/**
 * Generate the react entry source for one system. Binds the live RS
 * primitives roster to this system: one configurePrimitives call carries
 * the layer name plus the compiled style prop list, and destructures the
 * 101 bound components. The primitives path points at the tracked RS
 * generated source, never the gitignored dist build. The css() binding is
 * caller-provided: the publisher prepends a runtime header that imports
 * the style runtime plus this system's runtime-data, registers both, and
 * re-exports css/recipe — styled stays data-only. No react-dom
 * re-export: consumers bring their own copy, so the entry stays react-only
 * and packages built on it import clean without react-dom (retired reference-core contract).
 */
export function generateReactEntrySource(input: ReactEntryInput): string {
  const bound = ELEMENT_JSX_NAMES
  const lines = [
    '/** Generated by ref sync — do not edit manually */',
    `import { configurePrimitives, ColorModeContext, DocumentContext, Fragment, LayerScopeContext, createElement, useColorMode } from ${JSON.stringify(input.primitivesPath)}`,
    '',
    `export const { ${bound.join(', ')} } = configurePrimitives({ layerName: ${JSON.stringify(input.systemName)}, stylePropNames: ${JSON.stringify([...input.stylePropNames])}, css })`,
    'export { ColorModeContext, DocumentContext, Fragment, LayerScopeContext, createElement, useColorMode }',
    '',
  ]
  return lines.join('\n')
}

function stylePropUnion(stylePropNames: readonly string[]): string {
  const names = [...stylePropNames].sort()
  if (names.length === 0) return 'never'
  return names.map(name => JSON.stringify(name)).join(' | ')
}

function primitiveTagUnion(): string {
  return ELEMENT_DOM_TAGS.map(tag => JSON.stringify(tag)).join(' | ')
}

function toPascalCase(name: string): string {
  let out = ''
  let capNext = true
  for (const ch of name) {
    if (!/[A-Za-z0-9]/.test(ch)) {
      capNext = true
      continue
    }
    out += capNext ? ch.toUpperCase() : ch
    capNext = false
  }
  return out
}

function isTsIdent(name: string): boolean {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name)
}

function hasVariantFields(recipe: unknown): boolean {
  if (typeof recipe !== 'object' || recipe === null) return false
  const variants = (recipe as Record<string, unknown>).variants
  if (typeof variants !== 'object' || variants === null) return false
  return Object.values(variants).some(
    axis => typeof axis === 'object' && axis !== null && Object.keys(axis).length > 0
  )
}

/**
 * Derive the typegen recipe alias names one system's spec recipes print.
 * Mirrors the RS recipe printer exactly: PascalCase the recipe name, keep
 * TypeScript identifiers with at least one non-empty variant axis, append
 * VariantProps. Sorted and deduplicated so the union is stable.
 */
export function recipeVariantTypeNames(recipes: Record<string, unknown>): string[] {
  const stems: string[] = []
  for (const [name, recipe] of Object.entries(recipes)) {
    if (!hasVariantFields(recipe)) continue
    const stem = toPascalCase(name)
    if (!isTsIdent(stem)) continue
    stems.push(`${stem}VariantProps`)
  }
  return [...new Set(stems)].sort()
}

function styledImportLine(variantStems: readonly string[]): string {
  const names = ['StyleConditionKey', 'StyleProps as NarrowStyleProps', 'SystemStyleObject', ...variantStems]
  return `import type { ${names.join(', ')} } from '@reference-ui/styled'`
}

/** Names of the three style types the bound declarations read. */
interface StyleTypeNames {
  stylePropName: string
  styleProps: string
  primitiveCssProp: string
}

/** The publisher declares these; the register routes the public names through them. */
const LOCAL_STYLE_NAMES: StyleTypeNames = {
  stylePropName: 'LocalStylePropName',
  styleProps: 'LocalStyleProps',
  primitiveCssProp: 'LocalPrimitiveCssProp',
}

/** Every other role declares the public names outright. */
const PUBLIC_STYLE_NAMES: StyleTypeNames = {
  stylePropName: 'StylePropName',
  styleProps: 'StyleProps',
  primitiveCssProp: 'PrimitiveCssProp',
}

/**
 * The style type block. A publisher declares the Local* set and emits the
 * register after it; every other role declares the public names directly, so
 * its lines are the pre-register lines with no register at all.
 */
function styleTypeLines(union: string, variantStems: readonly string[], role: SyncedRole): string[] {
  const names = role === 'publisher' ? LOCAL_STYLE_NAMES : PUBLIC_STYLE_NAMES
  return [
    '/** Compiled style prop names: the styling keys every primitive accepts. */',
    `export type ${names.stylePropName} = ${union}`,
    styledImportLine(variantStems),
    '/** React style props: typegen precision where tokens exist, open everywhere else. */',
    `export type ${names.styleProps} = Omit<NarrowStyleProps, 'font' | 'weight'> & {`,
    `  [K in Exclude<${names.stylePropName}, keyof NarrowStyleProps> | 'font' | 'weight']?: unknown`,
    '} & {',
    `  [K in StyleConditionKey]?: ${names.styleProps}`,
    '}',
    `export type ${names.primitiveCssProp} = Omit<SystemStyleObject, 'font' | 'weight'> & { font?: unknown; weight?: unknown }`,
    ...(role === 'publisher' ? publisherRegisterLines() : []),
  ]
}

/**
 * The publisher's register. SyncedSystem is empty in lib's own build, so the
 * public names fall back to the Local* set; a consumer's fill replaces them.
 */
function publisherRegisterLines(): string[] {
  return [
    "/** Register a consumer fills through a module augmentation of lib; empty keeps lib's own types. */",
    'export interface SyncedSystem {}',
    `export type StylePropName = SyncedSystem extends { stylePropName: infer V } ? V : ${LOCAL_STYLE_NAMES.stylePropName}`,
    `export type StyleProps = SyncedSystem extends { styleProps: infer V } ? V : ${LOCAL_STYLE_NAMES.styleProps}`,
    `export type PrimitiveCssProp = SyncedSystem extends { cssProp: infer V } ? V : ${LOCAL_STYLE_NAMES.primitiveCssProp}`,
  ]
}

/**
 * The consumer's fill: a module augmentation that points lib's SyncedSystem at
 * this project's synced style types. It names them through this file's own
 * path (the react leg always writes react.d.mts), never by bare name: inside an
 * augmentation a bare name resolves against lib's exports first, so a bare
 * StyleProps there is lib's register alias, which reads SyncedSystem, which is
 * this fill, a cycle (TS2456, TS2502). A qualified name adds no declaration, so
 * nothing new leaks into this file's exports. Only the consumer role appends
 * it; a publisher must never fill its own register (a second declaration is TS2717).
 */
function consumerFillLines(role: SyncedRole): string[] {
  if (role !== 'consumer') return []
  return [
    "/** Fills lib's SyncedSystem register with this project's synced style types. */",
    "declare module '@reference-ui/lib' {",
    '  interface SyncedSystem {',
    "    styleProps: import('./react.d.mts').StyleProps",
    "    cssProp: import('./react.d.mts').PrimitiveCssProp",
    "    stylePropName: import('./react.d.mts').StylePropName",
    '  }',
    '}',
    '',
  ]
}

function perTagDecls(): string[] {
  const lines: string[] = []
  for (const { dom: tag, jsx: name } of ELEMENT_ROSTER) {
    lines.push(
      `export type ${name}Props = Omit<React.ComponentPropsWithoutRef<${JSON.stringify(tag)}>, StylePropName | 'css' | 'colorMode' | 'variant'> & StyleProps & { css?: PrimitiveCssProp; colorMode?: unknown; variant?: unknown }`,
      `export declare const ${name}: (props: ${name}Props & { ref?: React.Ref<React.ComponentRef<${JSON.stringify(tag)}>> }) => React.ReactNode`,
      ''
    )
  }
  return lines
}

/** `'base'` plus each recipe breakpoint, quoted and deduplicated in scale order. */
function recipeBreakpointUnion(breakpoints: readonly string[]): string {
  return [...new Set(['base', ...breakpoints])].map(name => JSON.stringify(name)).join(' | ')
}

/** Recipe selection, split and runtime-fn declarations, keyed by this system's recipe breakpoints. */
function recipeTypeLines(breakpointUnion: string): string[] {
  return [
    '/** Breakpoint keys a recipe value object takes: `base` plus the breakpoints recipe classes exist for. */',
    `export type RecipeBreakpointKey = ${breakpointUnion}`,
    '/** Breakpoint object for one variant value: `base` applies below every query. */',
    'export type RecipeResponsiveValue<T> = { [K in RecipeBreakpointKey]?: T }',
    '/** Values one axis accepts: its option keys (numeric ones in either spelling), plus booleans for `true`/`false` keys. */',
    'export type RecipeOptionValue<O> =',
    '  | Extract<keyof O, string>',
    '  | Extract<keyof O, number>',
    `  | \`\${Extract<keyof O, number>}\``,
    "  | ([Extract<keyof O, 'true' | 'false'>] extends [never] ? never : boolean)",
    '/** Selection for one variants table: every axis optional, plain or responsive. */',
    'export type RecipeVariantSelection<V> = {',
    '  [K in keyof V]?: RecipeOptionValue<V[K]> | RecipeResponsiveValue<RecipeOptionValue<V[K]>>',
    '}',
    '/** Variant selection inferred from one recipe fn config: every axis optional. */',
    'export type RecipeVariantProps<T> = T extends RecipeRuntimeFn<infer C>',
    `  ? C extends { variants: infer V extends Record<string, Record<string, unknown>> }`,
    '    ? RecipeVariantSelection<V>',
    '    : Record<string, RecipePropValue | undefined | null>',
    '  : Record<string, RecipePropValue | undefined | null>',
    '/** Axis names of one recipe config; never when it has no variants. */',
    'export type RecipeVariantKey<TConfig> = TConfig extends { variants: infer V } ? Extract<keyof V, string> : never',
    '/** Selection one recipe config takes; empty when it has no variants. */',
    'export type RecipeConfigSelection<TConfig> = TConfig extends { variants: infer V } ? RecipeVariantSelection<V> : {}',
    '/** Omit applied to each member of a union, so narrowing still works on the result. */',
    'export type DistributiveOmit<T, K extends PropertyKey> = T extends unknown ? Omit<T, K> : never',
    '/** Slot names of one recipe config; never when it lists no `slots`. */',
    'export type RecipeSlotName<TConfig> = TConfig extends { slots: readonly (infer S extends string)[] } ? S : never',
    '/** What one recipe call returns: a class string, or one class string per slot. */',
    'export type RecipeClasses<TConfig> = [RecipeSlotName<TConfig>] extends [never] ? string : Record<RecipeSlotName<TConfig>, string>',
    '/** What raw() returns: one style object, or one per slot. */',
    'export type RecipeRawStyles<TConfig> = [RecipeSlotName<TConfig>] extends [never] ? RecipeStyleObject : Record<RecipeSlotName<TConfig>, RecipeStyleObject>',
    '/** Resolved recipe function: classes for a selection plus variant metadata. */',
    '/** Call positions route through RecipeVariantProps<RecipeRuntimeFn<TConfig>>: */',
    '/** RecipeVariantProps<TConfig> would miss the fn-config infer and fall wide. */',
    'export interface RecipeRuntimeFn<TConfig extends RecipeConfig = RecipeConfig> {',
    '  (props?: RecipeVariantProps<RecipeRuntimeFn<TConfig>>): RecipeClasses<TConfig>',
    '  raw(props?: RecipeVariantProps<RecipeRuntimeFn<TConfig>>): RecipeRawStyles<TConfig>',
    '  variantKeys: string[]',
    '  variantMap: Record<string, string[]>',
    // P is bound by the selection with no intersection on the param: an intersection lets
    // 'nope' & { base? } through and breaks generic wrappers. The `& object` keeps the bound from
    // being weak, so props with no axis key pass. A recipe with no variants binds P to object only.
    // The variants half is picked from P, matching the runtime, so it keeps the caller's value
    // types. A bare RecipeRuntimeFn knows no axes, so either half may hold any of P's props.
    '  /** Split props into `[variants, rest]`: the recipe selection, and every other prop. */',
    '  splitVariantProps<P extends RecipeConfigSelection<TConfig> & object>(',
    '    props: P',
    '  ): RecipeConfig extends TConfig',
    '    ? [Partial<P>, Partial<P>]',
    '    : [Pick<P, Extract<keyof P, RecipeVariantKey<TConfig>>>, DistributiveOmit<P, RecipeVariantKey<TConfig>>]',
    '}',
  ]
}

function namedGraphLines(breakpointUnion: string): string[] {
  return [
    `export type * from '@reference-ui/styled'`,
    '/** One css() input: a style object, a list of them, or a conditional skip. */',
    'export type CssStyles = SystemStyleObject | undefined | null | false',
    '/** Shared prop shape every primitive accepts: native props for one tag plus style props and primitive extras. */',
    'export type PrimitiveProps<T extends PrimitiveTag> = Omit<',
    '  React.ComponentPropsWithoutRef<T>,',
    `  StylePropName | 'css' | 'colorMode' | 'variant'`,
    '> & StyleProps & {',
    '  css?: PrimitiveCssProp',
    '  colorMode?: unknown',
    '  variant?: unknown',
    '}',
    'export declare function css(...styles: Array<CssStyles | CssStyles[]>): string',
    '/** Wide authoring object for recipe configs: recipes are authored TS, not typegen. */',
    'export type RecipeStyleObject = Record<string, unknown>',
    '/** One variant axis value an author may pass. */',
    'export type RecipePropValue = string | boolean | number',
    '/** One compound rule: axis predicates plus the styles applied when all match. */',
    'export interface RecipeCompoundConfig {',
    '  css: RecipeStyleObject',
    '  [axis: string]: unknown',
    '}',
    '/** Authored recipe: the className extraction keys on plus base, variants, compounds; `slots` keys each style position by part. */',
    'export interface RecipeConfig {',
    '  className: string',
    '  slots?: readonly string[]',
    '  base?: RecipeStyleObject',
    '  variants?: Record<string, Record<string, RecipeStyleObject>>',
    '  defaultVariants?: Record<string, string>',
    '  compoundVariants?: readonly RecipeCompoundConfig[]',
    '}',
    ...recipeTypeLines(breakpointUnion),
    'export declare function recipe<const TConfig extends RecipeConfig>(config: TConfig): RecipeRuntimeFn<TConfig>',
    '',
  ]
}

/**
 * Generate the bound react entry types for one system. Every tag gets a
 * props type plus a ref-as-prop component signature; the styled wiring and
 * the named graph arrive complete, so no later leg rewrites this file.
 * StylePropName is the compiled list verbatim (the splitter's list);
 * css narrows to SystemStyleObject; per-tag variant stays open
 * unknown so user-space spreads compile, while the exported
 * PrimitiveVariantProp alias carries the union of this system's typegen
 * recipe aliases, never when recipes are absent. PrimitiveProps<T>
 * reuses the primitive types text verbatim.
 */
export function generateReactTypesSource(input: ReactTypesInput): string {
  const role = input.role ?? 'none'
  const union = stylePropUnion(input.stylePropNames)
  const variantStems = recipeVariantTypeNames(input.recipes)
  const variantUnion = variantStems.length === 0 ? 'never' : variantStems.join(' | ')
  const lines = [
    '/** Generated by ref sync — do not edit manually */',
    `import type * as React from 'react'`,
    '',
    ...styleTypeLines(union, variantStems, role),
    '/** Per-system variant selection: this system recipe unions, never when recipes are absent. */',
    `export type PrimitiveVariantProp = ${variantUnion}`,
    '',
    '/** Every platform tag the generated primitives cover. */',
    `export type PrimitiveTag = ${primitiveTagUnion()}`,
    '',
    '/** React types two tags with the generic HTMLElement instead of the real host. */',
    'interface PrimitiveElementOverrides {',
    '  caption: HTMLTableCaptionElement',
    '  menu: HTMLMenuElement',
    '}',
    '/** Host element for one tag, with the caption/menu overrides applied. */',
    'export type PrimitiveElement<T extends PrimitiveTag> = T extends keyof PrimitiveElementOverrides ? PrimitiveElementOverrides[T] : React.ComponentRef<T>',
    '',
    ...perTagDecls(),
    'export declare const LayerScopeContext: React.Context<boolean>',
    'export declare const ColorModeContext: React.Context<string | undefined>',
    'export declare const DocumentContext: React.Context<Document | null>',
    'export declare function useColorMode(): string | undefined',
    `export { Fragment } from 'react'`,
    `export { createElement } from 'react'`,
    '',
    ...namedGraphLines(recipeBreakpointUnion(input.recipeBreakpoints ?? [])),
    ...consumerFillLines(role),
  ]
  return lines.join('\n')
}
