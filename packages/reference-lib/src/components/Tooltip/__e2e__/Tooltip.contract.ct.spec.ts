import { test, expect, pressTab } from '../../../../playwright/ct'

test.describe('Tooltip consumer and lifecycle contracts', () => {
  test('TT-CONTRACT-01: authored descriptions survive open and close with one live tooltip reference', async ({ mount, page }) => {
    await mount('components/Tooltip/Tooltip.contract/Contracts')
    const trigger = page.getByTestId('trigger')
    const content = page.getByTestId('content')
    await page.getByTestId('before').focus()
    await pressTab(page)
    await expect(trigger).toBeFocused()
    await expect(content).toBeVisible()
    const id = await content.getAttribute('id')
    expect(id).toBeTruthy()
    await expect(trigger).toHaveAttribute('aria-describedby', `contract-description ${id}`)
    await expect(page.getByTestId('events')).toHaveText('consumer-focus,open,change:true')
    await page.keyboard.press('Escape')
    await expect(content).toHaveCount(0)
    await expect(trigger).toHaveAttribute('aria-describedby', 'contract-description')
    await expect(trigger).toBeFocused()
    await expect(page.getByTestId('events')).toHaveText('consumer-focus,open,change:true,change:false,dismiss')
  })

  test('TT-CONTRACT-02: consumer prevention cancels pointer and keyboard focus opening', async ({ mount, page }) => {
    await mount('components/Tooltip/Tooltip.contract/Contracts', { cancel: true })
    await page.getByTestId('trigger').hover()
    await page.waitForTimeout(300)
    await expect(page.getByTestId('content')).toHaveCount(0)
    await expect(page.getByTestId('events')).toHaveText('consumer-enter')
    await page.mouse.move(0, 0)
    await page.getByTestId('before').focus()
    await pressTab(page)
    await expect(page.getByTestId('trigger')).toBeFocused()
    await expect(page.getByTestId('content')).toHaveCount(0)
    await expect(page.getByTestId('events')).toHaveText('consumer-enter,consumer-focus')
  })

  test('TT-CONTRACT-03: controlled requests stay closed until the owner updates and updates emit no requests', async ({ mount, page }) => {
    await mount('components/Tooltip/Tooltip.contract/Contracts', { controlled: true })
    await page.getByTestId('before').focus()
    await pressTab(page)
    await expect(page.getByTestId('events')).toHaveText('consumer-focus,open,change:true')
    await expect(page.getByTestId('content')).toHaveCount(0)
    // Owner updates must be isolated from outside-pointer dismissal.
    await page.getByTestId('set-open').evaluate(element => (element as HTMLButtonElement).click())
    await expect(page.getByTestId('content')).toBeVisible()
    await expect(page.getByTestId('events')).toHaveText('consumer-focus,open,change:true')
    await page.getByTestId('set-closed').evaluate(element => (element as HTMLButtonElement).click())
    await expect(page.getByTestId('content')).toHaveCount(0)
    await expect(page.getByTestId('events')).toHaveText('consumer-focus,open,change:true')
  })

  test('TT-CONTRACT-04: unmount cancels delayed opening and remount starts a fresh session', async ({ mount, page }) => {
    await mount('components/Tooltip/Tooltip.contract/Contracts')
    await page.getByTestId('trigger').hover()
    await expect(page.getByTestId('events')).toHaveText('consumer-enter')
    await page.getByTestId('toggle-mount').evaluate(element => (element as HTMLButtonElement).click())
    await expect(page.getByTestId('trigger')).toHaveCount(0)
    await page.waitForTimeout(300)
    await expect(page.getByTestId('content')).toHaveCount(0)
    await expect(page.getByTestId('events')).toHaveText('consumer-enter')
    await page.mouse.move(0, 0)
    await page.getByTestId('toggle-mount').click()
    await expect(page.getByTestId('trigger')).toBeVisible()
    await expect(page.getByTestId('content')).toHaveCount(0)
    await page.getByTestId('trigger').hover()
    await expect(page.getByTestId('content')).toBeVisible()
    await expect(page.getByTestId('events')).toHaveText('consumer-enter,consumer-enter,open,change:true')
  })
})
