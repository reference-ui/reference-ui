// B-11: fail when the shippable dist/ is older than the sources it was built
// from. dist/ is git-ignored, so staleness is a local/pack-time hazard: a
// file:-linked consumer silently runs last week's behavior. CI runs
// build -> check:dist -> pack -> smoke; humans run `pnpm check:dist`.
import { readdir, stat } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const INPUT_ROOTS = ['src', 'book']
const INPUT_FILES = [
  'package.json',
  'tsup.config.ts',
  'tsconfig.build.json',
  'ui.config.ts',
  'scripts/build-package.mjs',
  'scripts/materialize-runtime.mjs',
]
// .reference-ui/ is generated by `ref sync` inside `pnpm build`; its mtime
// follows src, so src-vs-dist comparison subsumes it.
const REQUIRED_OUTPUTS = [
  'dist/index.mjs',
  'dist/index.d.ts',
  'dist/theme/index.mjs',
  'dist/runtime/reference-ui/react/react.mjs',
  'dist/runtime/reference-ui/react/styles.css',
  'dist/runtime/reference-ui/styled/runtime-data.mjs',
]

// Only extensions that can change the artifact: tsup bundles code and
// `ref sync` extracts style call-sites from code. Docs/assets (.md, .png,
// snapshots) never affect dist, so they must not stale the gate.
const TRACKED_EXTENSIONS = new Set(['.ts', '.tsx', '.mts', '.cts', '.js', '.mjs', '.cjs', '.json'])

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue
    const full = join(dir, entry.name)
    if (entry.isDirectory()) {
      yield* walk(full)
      continue
    }
    if (TRACKED_EXTENSIONS.has(entry.name.slice(entry.name.lastIndexOf('.')))) yield full
  }
}

async function mtime(path) {
  return (await stat(path)).mtimeMs
}

const inputs = [...INPUT_FILES.map((f) => join(packageRoot, f))]
for (const root of INPUT_ROOTS) {
  for await (const file of walk(join(packageRoot, root))) inputs.push(file)
}

let newestInput = { path: null, mtimeMs: -Infinity }
for (const file of inputs) {
  const ms = await mtime(file).catch(() => null)
  if (ms === null) continue
  if (ms > newestInput.mtimeMs) newestInput = { path: file, mtimeMs: ms }
}

const missing = []
let oldestOutput = { path: null, mtimeMs: Infinity }
for (const rel of REQUIRED_OUTPUTS) {
  const full = join(packageRoot, rel)
  const ms = await mtime(full).catch(() => null)
  if (ms === null) {
    missing.push(rel)
    continue
  }
  if (ms < oldestOutput.mtimeMs) oldestOutput = { path: rel, mtimeMs: ms }
}

if (missing.length > 0) {
  console.error(`check:dist FAIL — dist outputs missing: ${missing.join(', ')}`)
  console.error('Run: pnpm --dir packages/reference-lib run build')
  process.exit(1)
}

if (newestInput.mtimeMs > oldestOutput.mtimeMs) {
  const inputRel = newestInput.path.slice(packageRoot.length + 1)
  console.error(
    `check:dist FAIL — ${inputRel} is newer than ${oldestOutput.path}; dist is stale (B-11).`,
  )
  console.error('Run: pnpm --dir packages/reference-lib run build')
  process.exit(1)
}

console.log(
  `check:dist OK — ${inputs.length} inputs predate ${REQUIRED_OUTPUTS.length} dist outputs.`,
)
