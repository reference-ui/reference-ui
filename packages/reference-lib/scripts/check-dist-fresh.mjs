// B-11: fail when the shippable dist/ (and the generated .reference-ui/system
// baseSystem payloads it ships) is older than the sources it was built from.
// dist/ is git-ignored, so staleness is a local/pack-time hazard: a file:-linked
// consumer silently runs last week's behavior. CI runs build -> check:dist ->
// pack -> smoke; humans run `pnpm check:dist`.
import { readdir, stat } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const INPUT_ROOTS = ['src', 'book']
const INPUT_FILES = [
  'package.json',
  'tsup.config.ts',
  'tsconfig.build.json',
  'ui.config.ts',
  'scripts/build-package.mjs',
  'scripts/materialize-runtime.mjs',
]
// Every generated artifact that must exist. The six dist/ outputs are emitted by
// tsup/tsc + build-package.mjs; the two `.reference-ui/system/` baseSystem
// outputs are generated by `ref sync` inside `pnpm build`. Listing the sync
// outputs directly means a token touch that was never re-synced fails this gate
// by name instead of relying on the src-vs-dist comparison to subsume it.
const REQUIRED_OUTPUTS = [
  'dist/index.mjs',
  'dist/index.d.ts',
  'dist/theme/index.mjs',
  'dist/runtime/reference-ui/react/react.mjs',
  'dist/runtime/reference-ui/react/styles.css',
  'dist/runtime/reference-ui/styled/runtime-data.mjs',
  '.reference-ui/system/baseSystem.mjs',
  '.reference-ui/system/baseSystem.d.mts',
]
// `sync/commit.ts` keeps an unchanged output's mtime, so the content-bearing
// sync output is compared against the sync inputs (config + source) rather than
// the packaging inputs above: a package.json edit must not false-fail a system
// that is byte-identical. Only `baseSystem.mjs` carries the synced system and is
// rewritten when tokens change; `baseSystem.d.mts` is a fixed type declaration
// that is required to exist but cannot drift, so freshness covers it by its
// sibling.
const SYNC_OUTPUT = '.reference-ui/system/baseSystem.mjs'
const SYNC_INPUTS = ['ui.config.ts']

// Only extensions that can change the artifact: tsup bundles code and
// `ref sync` extracts style call-sites from code. Docs/assets (.md, .png,
// snapshots) never affect dist, so they must not stale the gate.
const TRACKED_EXTENSIONS = new Set(['.ts', '.tsx', '.mts', '.cts', '.js', '.mjs', '.cjs', '.json'])

// Test-only files never ship: tsup does not bundle them and `ref sync`
// extracts nothing from them, so they must not stale the gate. Story and
// book files (*.story.tsx, *.book.tsx) are NOT excluded — their literals
// compile into shipped CSS (precedent: Tree.story.tsx `120r`).
function isTestOnly(full, name) {
  if (full.split('/').includes('__e2e__')) return true
  return name.includes('.test.') || name.includes('.spec.')
}

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue
    const full = join(dir, entry.name)
    if (entry.isDirectory()) {
      yield* walk(full)
      continue
    }
    if (isTestOnly(full, entry.name)) continue
    if (TRACKED_EXTENSIONS.has(entry.name.slice(entry.name.lastIndexOf('.')))) yield full
  }
}

async function mtime(path) {
  return (await stat(path)).mtimeMs
}

async function newestOf(files) {
  let newest = { path: null, mtimeMs: -Infinity }
  for (const file of files) {
    const ms = await mtime(file).catch(() => null)
    if (ms === null) continue
    if (ms > newest.mtimeMs) newest = { path: file, mtimeMs: ms }
  }
  return newest
}

async function rootInputs() {
  const files = []
  for (const root of INPUT_ROOTS) {
    for await (const file of walk(join(packageRoot, root))) files.push(file)
  }
  return files
}

const rootFiles = await rootInputs()
const inputs = [...INPUT_FILES.map((f) => join(packageRoot, f)), ...rootFiles]
const syncInputs = [...SYNC_INPUTS.map((f) => join(packageRoot, f)), ...rootFiles]
const newestInput = await newestOf(inputs)
const newestSyncInput = await newestOf(syncInputs)

const missing = []
const oldest = new Map()
for (const rel of REQUIRED_OUTPUTS) {
  const ms = await mtime(join(packageRoot, rel)).catch(() => null)
  if (ms === null) {
    missing.push(rel)
    continue
  }
  oldest.set(rel, ms)
}

if (missing.length > 0) {
  console.error(`check:dist FAIL — dist outputs missing: ${missing.join(', ')}`)
  console.error('Run: pnpm --dir packages/reference-lib run build')
  process.exit(1)
}

const distOutputs = REQUIRED_OUTPUTS.filter((rel) => rel.startsWith('dist/'))
const oldestDist = { path: distOutputs[0], mtimeMs: Infinity }
for (const rel of distOutputs) {
  if (oldest.get(rel) < oldestDist.mtimeMs) {
    oldestDist.path = rel
    oldestDist.mtimeMs = oldest.get(rel)
  }
}

const stale = []
if (newestInput.mtimeMs > oldestDist.mtimeMs) {
  stale.push({ input: newestInput, output: oldestDist.path })
}
if (newestSyncInput.mtimeMs > oldest.get(SYNC_OUTPUT)) {
  stale.push({ input: newestSyncInput, output: SYNC_OUTPUT })
}

if (stale.length > 0) {
  console.error('check:dist FAIL — dist is stale (B-11):')
  for (const { input, output } of stale) {
    console.error(`  ${input.path.slice(packageRoot.length + 1)} is newer than ${output}`)
  }
  console.error('Run: pnpm --dir packages/reference-lib run build')
  process.exit(1)
}

console.log(
  `check:dist OK — ${inputs.length} inputs predate ${REQUIRED_OUTPUTS.length} generated outputs.`,
)
